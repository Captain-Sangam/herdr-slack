// Builds mods/slack/emoji.js: Slack's standard emoji names (short names and aliases)
// mapped to Unicode code points, from iamcal/emoji-data, which Slack names its emoji after.
//   node scripts/gen-emoji.mjs
import { writeFileSync } from "node:fs";

const VERSION = "v16.0.0";
const SRC = `https://raw.githubusercontent.com/iamcal/emoji-data/${VERSION}/emoji.json`;

const res = await fetch(SRC);
if (!res.ok) throw new Error(`${SRC}: HTTP ${res.status}`);
const pairs = new Map();
for (const e of await res.json()) for (const name of e.short_names) pairs.set(name, e.unified.toLowerCase());
// Compact: "name hex-hex|name hex|…", parsed once when lib.js loads.
const body = [...pairs].sort(([a], [b]) => (a < b ? -1 : 1)).map(([n, u]) => `${n} ${u}`).join("|");
writeFileSync(new URL("../mods/slack/emoji.js", import.meta.url), [
  `// Generated by scripts/gen-emoji.mjs from iamcal/emoji-data ${VERSION}. Do not edit.`,
  `export const SOURCE = "iamcal/emoji-data ${VERSION}";`,
  `export default ${JSON.stringify(body)};`,
  "",
].join("\n"));
console.log(`${pairs.size} names`);
